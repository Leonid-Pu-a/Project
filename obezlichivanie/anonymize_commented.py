# 2. Детерминированный «случайный» выбор
# =====================================================================================
# Главная «хеш-функция» программы: из текста делаем большое число
def h(text):
    """Большое целое число из SHA-256(секрет + текст). Одинаковый текст -> одинаковое число."""
    # склеиваем секрет и текст, кодируем в байты, считаем SHA-256, 64 hex-символа превращаем в целое число
    return int(hashlib.sha256((SECRET + "|" + text).encode("utf-8")).hexdigest(), 16)


# Выбор элемента списка «случайно», но всегда одинаково для одного и того же текста
def pick(items, text):
    """Выбрать элемент списка по хешу текста."""
    # остаток от деления хеша на длину списка — это номер элемента (от 0 до len-1)
    return items[h(text) % len(items)]


