# Счётчики для итогового отчёта
stats = {"objects": 0, "persons": 0, "base64": 0}


# Решить, как заменить одно значение: cls — класс объекта, field — имя поля, person — ФИО сотрудника
def process_value(cls, field, value, person):
    # поля сотрудника (cim:Person): имя, фамилия, имя, отчество
    if cls == "Person" and field in ("IdentifiedObject.name", "Person.lastName", "Person.firstName", "Person.mName"):
        # считаем замену ФИО
        stats["persons"] += 1
        # синтетическое ФИО, заранее посчитанное для этого сотрудника
        sur, first, middle = person
        # для фамилии/имени/отчества — соответствующая часть, для name — полное ФИО
        return {"Person.lastName": sur, "Person.firstName": first, "Person.mName": middle}.get(
            # значение по умолчанию (для IdentifiedObject.name)
            field, f"{sur} {first} {middle}")

    # поле с ФИО ответственного в адресе
    if field in PERSON_FIELDS:                                         # «ответственный» в адресе
        # считаем замену ФИО
        stats["persons"] += 1
        # синтетическое ФИО
        return fake_person(value)

    # название абонента
    if cls == "Customer" and field == "IdentifiedObject.name":
        # похоже на ФИО — значит, физлицо
        if looks_like_person(value):                                   # физлицо
            # считаем
            stats["persons"] += 1
            # синтетическое ФИО
            return fake_person(value)
        # проверяем префиксы индивидуального предпринимателя
        for prefix in IP_PREFIXES:                                     # индивидуальный предприниматель
            # название начинается с этого префикса
            if value.startswith(prefix):
                # считаем
                stats["persons"] += 1
                # префикс оставляем, ФИО после него заменяем
                return prefix + fake_person(value[len(prefix):])
        # (организации и номера идут дальше — в общую обработку текста)

    # пробуем раскодировать base64
    raw = decode_base64(value)
    # это base64 —
    if raw is not None:
        # считаем вложение
        stats["base64"] += 1
        # обрабатываем вложение
        return process_base64(value, raw)

    # значение — число, дата или true/false, и это не поле-идентификатор и не название —
    if re.fullmatch(r"[-+]?\d*[.,]?\d+([eE][-+]?\d+)?|true|false|\d{4}-\d\d-\d\d.*", value) \
            and field not in ID_FIELDS and field not in NAME_FIELDS:
        # не трогаем: это сопротивления, длины, мощности — физика модели
        return value                                                   # числа, даты, флаги — физика модели

    # название-номер: у счётчика, точки учёта, опоры, абонента
    number_name = cls in NUMBER_NAME_CLASSES and field == "IdentifiedObject.name"   # «52073867» — номер счётчика
    # всё остальное — обычный текст; в полях-идентификаторах меняем все номера от 3 цифр
    return process_text(value, id_field=field in ID_FIELDS or number_name)


# Обработать один объект модели целиком
def process_object(obj):
    # класс объекта
    cls = local(obj.tag)
    # идентификатор объекта может быть в rdf:about или rdf:ID
    for attr in (RDF + "about", RDF + "ID"):
        # атрибут есть
        if obj.get(attr) is not None:
            # заменяем в нём UUID
            obj.set(attr, replace_uuids(obj.get(attr)))
    # Сотрудник (cim:Person): вместо логина «ck11user5» — синтетическое ФИО, одно на объект,
    # чтобы поля name, lastName, firstName одного сотрудника были согласованы.
    # для остальных классов ФИО сотрудника не нужно
    person = None
    # это сотрудник
    if cls == "Person":
        # ключ — идентификатор объекта (одинаковый для всех полей этого сотрудника)
        key = obj.get(RDF + "about") or ""
        # фамилия (колонка 1) латиницей
        person = (translit(pick(MALE, "p-surname:" + key)[1]),
                  # имя (колонка 0) латиницей
                  translit(pick(MALE, "p-first:" + key)[0]),
                  # отчество мужское (колонка 2) латиницей
                  translit(pick(MALE, "p-middle:" + key)[2]))
    # обходим все элементы объекта
    for el in obj.iter():
        # значение атрибута rdf:resource (ссылка), если есть
        res = el.get(RDF + "resource")
        # это ссылка
        if res is not None:
            # заменяем UUID в ссылке той же функцией, что и в rdf:about, — связь сохраняется
            el.set(RDF + "resource", replace_uuids(res))   # внешние ссылки (перечисления) без UUID не меняются
    # обходим все текстовые значения
    for el, field in leaf_values(obj):
        # заменяем значение по правилам
        el.text = process_value(cls, field, el.text, person)


# Второй проход: читать, обезличивать и писать в выходной файл
def anonymize(src, dst):
    # открываем исходный файл как байты
    with open(src, "rb") as f:                         # заголовок файла (<?xml ...?>, <rdf:RDF ...>) — как был
        # читаем первый мегабайт: в нём заголовок и корневой тег
        head = f.read(1 << 20)
    # ищем корневой тег <rdf:RDF ...> со всеми объявлениями пространств имён
    m = re.search(rb"<(\w+:)?RDF\b[^>]*>", head)
    # закрывающий тег корня: </rdf:RDF>
    root_close = b"</" + (m.group(1) or b"") + b"RDF>\n"
    # строки xmlns:..., которые нужно будет вырезать из каждого объекта
    declarations = None
    # открываем выходной файл на запись байтов
    with open(dst, "wb") as out:
        # пишем заголовок исходного файла как есть (до конца корневого тега)
        out.write(head[:m.end()] + b"\n")
        # перебираем объекты модели
        for obj in read_objects(src):
            # при первом объекте пространства имён уже прочитаны
            if declarations is None:                   # xmlns-атрибуты, которые ElementTree добавит в каждый объект
                # готовим строки вида ' xmlns:cim="http://..."'
                declarations = [f' xmlns:{p}="{u}"' for p, u in NAMESPACES.items()]
            # обезличиваем объект
            process_object(obj)
            # убираем «хвост» после объекта (перевод строки и отступ из исходного файла)
            obj.tail = None
            # превращаем объект обратно в XML-текст
            text = ET.tostring(obj, encoding="unicode")
            # ElementTree добавляет в каждый объект объявления пространств имён —
            for d in declarations:
                # вырезаем их, они уже есть в корневом теге
                text = text.replace(d, "")             # они уже объявлены на корне
            # пишем объект с отступом и переводом строки
            out.write(b"  " + text.encode("utf-8") + b"\n")
            # считаем объект
            stats["objects"] += 1
        # закрываем корневой тег
        out.write(root_close)


