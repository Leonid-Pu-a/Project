# Синтетическое ФИО вместо настоящего
def fake_person(full_name):
    """
    «Nikitin Vitaliy Artemov» -> «Petrov Kirill Romanovich».
    Фамилия, имя и отчество берутся из справочника по хешу соответствующей части,
    пол определяется по окончанию фамилии, алфавит и РЕГИСТР — как в исходной строке.
    """
    # делим ФИО на части по пробелам
    parts = full_name.split()
    # пустая строка — возвращаем как есть
    if not parts:
        # нечего заменять
        return full_name
    # женщина, если фамилия оканчивается на «a» (латиница) или «а» (кириллица): Petrova, Иванова
    female = parts[0].lower().endswith(("a", "а"))
    # фамилия: колонка 1 справочника (Петров), строка выбирается по хешу исходной фамилии
    surname = pick(MALE, "surname:" + parts[0])[1]
    # для женщины добавляем «а»: Петров → Петрова
    if female:
        # женская форма фамилии
        surname += "а"
    # начинаем собирать результат с фамилии
    result = [surname]
    # если есть имя (вторая часть)
    if len(parts) > 1:
        # имя из женского или мужского справочника, колонка 0
        result.append(pick(FEMALE if female else MALE, "first:" + parts[1])[0])
    # если есть отчество (третья часть)
    if len(parts) > 2:
        # отчество: колонка 3 (женское) или 2 (мужское)
        result.append(pick(MALE, "middle:" + parts[2])[3 if female else 2])
    # склеиваем части через пробел
    text = " ".join(result)
    # если исходное ФИО латиницей — переводим результат в латиницу
    if not is_cyrillic(full_name):
        # «Петров Кирилл» → «Petrov Kirill»
        text = translit(text)
    # если исходное ФИО написано ЗАГЛАВНЫМИ — результат тоже заглавными
    return text.upper() if full_name.isupper() else text


# Похоже ли название абонента на ФИО (а не на организацию)
def looks_like_person(name):
    """Три слова, каждое с заглавной буквы и только из букв — похоже на ФИО."""
    # делим на слова
    parts = name.split()
    # ровно 3 слова; каждое только из букв, с заглавной первой, и не целиком заглавными (не аббревиатура)
    return len(parts) == 3 and all(p.isalpha() and p[0].isupper() and not p.isupper() for p in parts)


# Синтетический e-mail вместо настоящего
def fake_email(email):
    """Адрес строится из синтетического имени: «ivanov@mail.ru» -> «pyotr.petrov17@example.com»."""
    # фамилия из справочника по хешу адреса, латиницей, строчными
    surname = translit(pick(MALE, "e-surname:" + email)[1]).lower()
    # имя из справочника по хешу адреса, латиницей, строчными
    first = translit(pick(MALE, "e-first:" + email)[0]).lower()
    # собираем адрес; домен example.com зарезервирован и никому не принадлежит
    return f"{first}.{surname}{h(email) % 100}@example.com"


# Синтетический телефон вместо настоящего (формат записи сохраняем)
def fake_phone(phone):
    """Последние 10 цифр телефона заменяем, формат записи (+7 (912) 345-67-89) сохраняем."""
    # оставляем только цифры: "+7 (912) 345-67-89" → "79123456789"
    digits = re.sub(r"\D", "", phone)
    # код страны оставляем, последние 10 цифр заменяем через new_number
    new = digits[:-10] + new_number(digits[-10:])
    # «итератор» по новым цифрам: будем брать их по одной
    position = iter(new)
    # каждую цифру исходной записи заменяем следующей новой цифрой — скобки, пробелы, дефисы остаются
    return re.sub(r"\d", lambda m: next(position), phone)


# --- 3.5 Замена внутри произвольного текста ---------------------------------------
# Номер после «типа объекта»: «Sub - 2303», «TS 1230-2», «РП 843», «pol.126», «№ 1234».
# Но «Sub 138 kV» и «Sub 110/35 kV» — это напряжение, его НЕ трогаем (проверка «(?!...)» после числа).
# Список «типов объектов», после которых идёт номер объекта (через | — «или»)
MARKERS = r"Sub|ПС|TS|ТП|KTP|КТП|STP|СТП|RP|РП|pol|оп|Оп|feeder|No|№"
# Единицы измерения: число перед ними — это напряжение/мощность, его не меняем
UNITS = r"kV|кВ|kv|KV|kVA|кВА|MVA|МВА|MW|МВт|V\b|В\b"
# ОДНО регулярное выражение со всеми видами «интересных кусков» текста; re.VERBOSE разрешает пробелы и переносы
TOKEN = re.compile(r"""
     (?P<uuid>""" + UUID_RE.pattern + r""")
   | (?P<email>[\w.+-]+@[\w-]+\.[\w.-]+)
   | (?P<phone>(?<![\d+])(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d))
   | (?P<marker>(?<![A-Za-zА-Яа-яЁё])(?:""" + MARKERS + r""")[\s.\-–_№]*)(?P<mnum>\d{3,})(?![\d/]|[.,]\d|\s*(?:""" + UNITS + r"""))
   | (?P<num>\d+)
   | (?P<word>[^\W\d_]+)
""", re.VERBOSE)
# Расшифровка шаблона TOKEN (варианты проверяются слева направо, срабатывает первый подошедший):
#   uuid   — идентификатор объекта;
#   email  — «что-то@домен.зона»;
#   phone  — +7 или 8, затем 10 цифр с любыми скобками/пробелами/дефисами;
#   marker — тип объекта (Sub, ПС, №...), разделители и номер из 3+ цифр (mnum),
#            после которого НЕ идёт: цифра, «/» (110/35), дробная часть (0,4 или 0.4), единица (kV);
#            обычная запятая после номера («Sub - 2303, …») разрешена;
#   num    — любое другое число;
#   word   — слово из букв (без цифр и подчёркиваний).


# Обработка произвольного текста: id_field — поле-идентификатор, long_numbers — менять ли длинные числа
def process_text(text, id_field=False, long_numbers=True):
    """
    Один проход регулярным выражением по тексту. Для каждого найденного куска решаем:
      UUID           -> новый UUID
      e-mail/телефон -> синтетические
      «Sub 2303»     -> номер объекта заменяем
      число          -> заменяем, если это поле-идентификатор (номер счётчика и т.п.)
                        или число длинное (6+ цифр: ИНН, лицевой счёт, код из учётной системы)
      слово          -> по словарям (имя собственное / улица); остальные слова не трогаем
    Каждый кусок текста заменяется ровно один раз.
    """
    # вложенная функция: получает найденный кусок m и возвращает, на что его заменить
    def replace(m):
        # имя сработавшей группы шаблона: "uuid", "email", "phone", "mnum", "num" или "word"
        kind = m.lastgroup
        # сам найденный текст
        t = m.group()
        # нашли UUID
        if kind == "uuid":
            # заменяем на новый UUID
            return new_uuid(t)
        # нашли e-mail
        if kind == "email":
            # заменяем на синтетический
            return fake_email(t)
        # нашли телефон
        if kind == "phone":
            # заменяем цифры, сохраняя формат
            return fake_phone(t)
        # нашли «тип объекта + номер» (последней закрылась группа mnum)
        if kind == "mnum":
            # тип и разделители оставляем, номер заменяем
            return m.group("marker") + new_number(m.group("mnum"))
        # нашли просто число
        if kind == "num":
            # меняем, если это поле-идентификатор (3+ цифр) или длинное число (6+ цифр)
            if (id_field and len(t) >= 3) or (long_numbers and len(t) >= 6):
                # новое число той же длины
                return new_number(t)
            # короткие числа (напряжение, номер фидера, «Т-2») не трогаем
            return t
        # дальше остался только вариант «слово»; районы и регионы не меняем
        if t in protected:
            # слово как есть
            return t
        # слово — название улицы
        if t in street_map:
            # замена из словаря улиц
            return street_map[t]
        # слово — имя собственное: берём замену; если слова нет в словаре — оставляем как есть
        return word_map.get(t, t)
    # применяем replace ко всем найденным кускам текста
    return TOKEN.sub(replace, text)


# --- 3.6 base64: вложенные XML-документы, zip-архивы схем -----------------------
# base64 — это только латинские буквы, цифры, «+», «/» и «=» в конце; длинная строка (40+ символов)
BASE64_RE = re.compile(r"[A-Za-z0-9+/]{40,}={0,2}")


# Попробовать раскодировать значение как base64
def decode_base64(value):
    """Возвращает байты, если значение похоже на base64, иначе None."""
    # длина base64 всегда кратна 4, и строка должна целиком подходить под шаблон
    if len(value) % 4 or not BASE64_RE.fullmatch(value):
        # не base64
        return None
    # пробуем раскодировать
    try:
        # validate=True: ошибка при посторонних символах
        return base64.b64decode(value, validate=True)
    # раскодировать не удалось
    except ValueError:
        # значит, не base64
        return None


# Достать тексты из раскодированных байтов (нужно в проходе 1, чтобы искать в них названия)
def base64_texts(raw):
    """Все тексты внутри base64: сам текст или XML-файлы из zip. Картинки/звук — пропускаем."""
    # zip-архив всегда начинается с байтов «PK»
    if raw[:2] == b"PK":
        # открываем архив прямо в памяти
        with zipfile.ZipFile(io.BytesIO(raw)) as z:
            # читаем все .xml-файлы архива как текст (utf-8-sig убирает метку BOM в начале)
            return [z.read(n).decode("utf-8-sig", "ignore") for n in z.namelist() if n.endswith(".xml")]
    # не архив — пробуем прочитать байты как текст
    try:
        # получилось — это текст (например, XML участков линии)
        return [raw.decode("utf-8-sig")]
    # не получилось — это двоичные данные
    except UnicodeDecodeError:
        # картинку или звук не обрабатываем
        return []


# Обработать base64-значение: раскодировать, заменить, закодировать обратно
def process_base64(value, raw):
    # вложенная функция: обработать байты текстового файла
    def fix(data):                                  # обработать текст, сохранив BOM, если был
        # запоминаем, была ли метка BOM (три байта EF BB BF в начале файла)
        bom = data.startswith(b"\xef\xbb\xbf")
        # заменяем в тексте всё как обычно, но длинные числа не трогаем (в схемах это координаты)
        text = process_text(data.decode("utf-8-sig"), long_numbers=False)  # координаты схем не трогаем
        # возвращаем байты, вернув BOM на место, если он был
        return (b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8")

    # это zip-архив
    if raw[:2] == b"PK":                            # zip-архив (схема подстанции)
        # новый архив будем собирать в памяти
        out = io.BytesIO()
        # открываем старый архив (zin) на чтение и новый (zout) на запись
        with zipfile.ZipFile(io.BytesIO(raw)) as zin, zipfile.ZipFile(out, "w") as zout:
            # перебираем файлы старого архива
            for info in zin.infolist():
                # читаем содержимое файла
                data = zin.read(info)
                # .xml-файлы обрабатываем, остальные кладём как есть; info сохраняет имя и способ сжатия
                zout.writestr(info, fix(data) if info.filename.endswith(".xml") else data)
        # новый архив кодируем в base64 и возвращаем строкой
        return base64.b64encode(out.getvalue()).decode("ascii")
    # не архив — проверяем, текст ли это
    try:
        # пробная расшифровка как текст
        raw.decode("utf-8-sig")
    # не текст
    except UnicodeDecodeError:
        # двоичные данные возвращаем без изменений
        return value                                # двоичные данные (картинка, звук, график)
    # текст: обрабатываем и кодируем обратно в base64
    return base64.b64encode(fix(raw)).decode("ascii")


