# Строим словарь замен для всех найденных имён собственных
def build_word_map(words):
    """
    Каждому слову — своё прилагательное. Слова сортируем и нумеруем:
      0..99    -> «Яблочная»
      100..    -> «Яблочно-грушевая» (две РАЗНЫЕ части), так хватит на 100 + 100*99 = 10 000 слов.
    Номера у слов разные => и замены разные (уникальность новых наименований).
    Сортируем НЕ по алфавиту, а по хешу с секретом: иначе по номеру прилагательного можно было бы
    угадать алфавитное место настоящего названия. Порядок всё равно одинаковый при каждом запуске.
    """
    # сортируем слова по хешу (а при равном хеше — по самому слову): порядок зависит от секрета
    words = sorted(words, key=lambda w: (h("word:" + w), w))
    # сколько у нас фруктов-прилагательных (100)
    n = len(FRUITS)
    # если слов больше, чем вариантов замен, — останавливаемся с понятным сообщением
    if len(words) > n + n * (n - 1):
        # SystemExit завершает программу и печатает текст
        raise SystemExit("Слишком много имён собственных — добавьте фруктов в dict/fruits.tsv")
    # перебираем слова вместе с их порядковым номером i (0, 1, 2, ...)
    for i, word in enumerate(words):
        # первые n слов получают одно прилагательное
        if i < n:
            # i-е прилагательное из справочника
            adjective = FRUITS[i]                           # «Яблочная»
        # остальные — составное из двух разных
        else:
            # номер пары: first — первая часть, second — вторая (от 0 до n-2)
            first, second = divmod(i - n, n - 1)            # номер пары (first, second), first != second
            # пропускаем вариант «одинаковые части»: сдвигаем second, если он >= first
            if second >= first:
                # теперь second никогда не равен first
                second += 1
            # первая часть: «Яблочная» без «ая» + «о» = «Яблочно»
            prefix = FRUITS[first][:-2] + "о"               # «Яблочная» -> «Яблочно»
            # склеиваем: «Яблочно» + «-» + «грушевая»
            adjective = prefix + "-" + FRUITS[second].lower()
        # если исходное слово латиницей — замену тоже пишем латиницей
        if not is_cyrillic(word):
            # «Яблочная» → «Yablochnaya»
            adjective = translit(adjective)
        # если исходное слово целиком ЗАГЛАВНЫМИ (и длиннее 1 буквы) — замену тоже заглавными
        if word.isupper() and len(word) > 1:
            # «KOLRABIEVY» → «YABLOCHNAYA»
            adjective = adjective.upper()
        # запоминаем замену
        word_map[word] = adjective


# Строим словарь замен для названий улиц
def build_street_map(words):
    # для каждого слова из названий улиц
    for word in words:
        # по хешу выбираем строку справочника имён и берём колонку «Улица» (индекс 4)
        street = pick(MALE, "street:" + word)[4]               # «Петровская»
        # латиница для латинских названий, кириллица — для русских
        street_map[word] = street if is_cyrillic(word) else translit(street)


