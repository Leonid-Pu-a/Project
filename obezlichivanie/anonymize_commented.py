# --- 3.1 UUID (идентификаторы объектов) -------------------------------------------
# Шаблон UUID: 8-4-4-4-12 шестнадцатеричных символов, например 3ca10967-b797-4d15-9a44-cdea3015ad63
UUID_RE = re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")


# Новый UUID для старого
def new_uuid(old):
    """Новый UUID из старого. Регистр букв сохраняем (в схемах бывают ЗАГЛАВНЫЕ UUID)."""
    # хеш старого UUID (в нижнем регистре, чтобы «ABC» и «abc» дали одно и то же) → 128-битное число → UUID версии 4
    new = str(uuid.UUID(int=h("uuid:" + old.lower()) % 2 ** 128, version=4))
    # если старый UUID был записан заглавными буквами — возвращаем новый тоже заглавными
    return new.upper() if old.isupper() else new


# Заменить все UUID внутри строки (например, "#_3ca10967-..." в rdf:resource)
def replace_uuids(text):
    # sub находит каждое совпадение с шаблоном и подставляет результат new_uuid
    return UUID_RE.sub(lambda m: new_uuid(m.group()), text)


# --- 3.2 Номера (той же длины, без повторов) --------------------------------------
# Запоминаем уже сделанные замены номеров: старый → новый
number_map = {}          # старый номер -> новый
# Множество выданных новых номеров: чтобы два разных старых номера не получили один новый
used_numbers = set()     # уже выданные новые номера (чтобы два разных номера не совпали)


# Новый номер той же длины для старого номера (строки из цифр)
def new_number(old):
    # если этот номер уже заменяли — возвращаем ту же замену (согласованность во всём файле)
    if old in number_map:
        # та же замена, что и раньше
        return number_map[old]
    # номер попытки: если кандидат не подошёл, пробуем следующий
    attempt = 0
    # повторяем, пока не найдём подходящий новый номер
    while True:
        # кандидат: хеш → остаток от деления на 10^длина → дополняем нулями слева до нужной длины
        new = str(h(f"num:{old}:{attempt}") % 10 ** len(old)).zfill(len(old))
        # «вид» номера сохраняем: если старый начинался с 0 — и новый с 0, иначе — не с 0
        same_kind = (new[0] == "0") == (old[0] == "0")       # «0123» -> «0xxx», «123» -> не «0xx»
        # кандидат подходит: правильный вид, не совпадает со старым и ещё никому не выдан
        if same_kind and new != old and new not in used_numbers:
            # выходим из цикла — номер найден
            break
        # иначе пробуем следующую попытку
        attempt += 1
    # запоминаем замену
    number_map[old] = new
    # отмечаем новый номер как занятый
    used_numbers.add(new)
    # возвращаем новый номер
    return new


