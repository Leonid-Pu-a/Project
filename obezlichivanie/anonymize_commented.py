# Функция чтения справочника: имя файла → список строк, каждая строка — список колонок
def load_tsv(name):
    """Читает файл справочника: строки, разделённые табуляцией; '#' — комментарий."""
    # сюда складываем прочитанные строки
    rows = []
    # открываем файл dict/<name> в кодировке UTF-8 (в нём кириллица)
    with open(os.path.join(HERE, "dict", name), encoding="utf-8") as f:
        # читаем файл построчно
        for line in f:
            # убираем пробелы и перевод строки по краям
            line = line.strip()
            # пропускаем пустые строки и комментарии (начинаются с #)
            if line and not line.startswith("#"):
                # делим строку по табуляции на колонки и сохраняем
                rows.append(line.split("\t"))
    # возвращаем все строки справочника
    return rows


# Мужские имена: каждая строка [Имя, Фамилия, Отчество муж., Отчество жен., Улица]
MALE = load_tsv("names.tsv")             # [Имя, Фамилия, Отчество_м, Отчество_ж, Улица]
# Женские имена: каждая строка [Имя]
FEMALE = load_tsv("female_names.tsv")    # [Имя]
# Из справочника фруктов берём только вторую колонку — прилагательное («Яблочная»)
FRUITS = [row[1] for row in load_tsv("fruits.tsv")]   # прилагательные: «Яблочная», ...

# Таблица транслитерации: каждой русской букве (первая строка) — латинские буквы (список)
TRANSLIT = dict(zip("абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
                    # латинские соответствия для а...п
                    ["a", "b", "v", "g", "d", "e", "yo", "zh", "z", "i", "y", "k", "l", "m", "n", "o",
                     # латинские соответствия для п...я («ъ» и «ь» не пишем)
                     "p", "r", "s", "t", "u", "f", "kh", "ts", "ch", "sh", "shch", "", "y", "", "e", "yu", "ya"]))


# Перевод русского текста в латиницу (нужен, когда исходное название записано латиницей)
def translit(text):
    """Кириллица -> латиница: «Яблочная» -> «Yablochnaya»."""
    # результат собираем в строку
    out = ""
    # перебираем символы по одному
    for ch in text:
        # ищем латинский вариант строчной буквы; если буквы нет в таблице — оставляем символ как есть
        lat = TRANSLIT.get(ch.lower(), ch)
        # если исходная буква заглавная — делаем заглавной первую латинскую букву («Я» → «Ya»)
        out += lat.capitalize() if ch.isupper() else lat
    # возвращаем латинский текст
    return out


# Проверка: есть ли в тексте хотя бы одна русская буква
def is_cyrillic(text):
    # re.search ищет первую русскую букву; None означает «не нашли»
    return re.search("[А-Яа-яЁё]", text) is not None


