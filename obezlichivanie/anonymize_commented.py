# Генератор: отдаёт объекты модели по одному, не загружая весь файл в память
def read_objects(path):
    """Отдаёт объекты верхнего уровня (дочерние элементы rdf:RDF) по одному."""
    # текущая глубина вложенности тегов
    depth = 0
    # корневой элемент rdf:RDF
    root = None
    # iterparse сообщает о событиях: начало тега, конец тега, объявление пространства имён
    for event, elem in ET.iterparse(path, events=("start", "end", "start-ns")):
        # встретили объявление xmlns:префикс="URI"
        if event == "start-ns":
            # elem в этом случае — пара (префикс, URI)
            prefix, uri = elem
            # запоминаем для записи файла
            NAMESPACES[prefix] = uri
            # сообщаем ElementTree префикс, иначе при записи он напишет ns0:, ns1:
            ET.register_namespace(prefix, uri)        # чтобы при записи остались cim:, me:, rdf:
        # начало тега
        elif event == "start":
            # спускаемся на уровень глубже
            depth += 1
            # глубина 1 — это корень rdf:RDF
            if depth == 1:
                # запоминаем корень
                root = elem
        # конец тега
        else:
            # поднимаемся на уровень выше
            depth -= 1
            # закрылся тег глубины 2 → после уменьшения глубина 1: это целиком прочитанный объект модели
            if depth == 1:
                # отдаём объект вызывающему коду (здесь функция «замирает» до следующего запроса)
                yield elem
                # объект обработан — удаляем его из дерева, чтобы не копить память
                root.remove(elem)                     # освобождаем память


# Генератор: все текстовые значения объекта (в том числе вложенные, например части адреса)
def leaf_values(obj):
    """Все текстовые значения объекта (включая вложенные, например адрес): (элемент, поле)."""
    # iter() обходит сам объект и все вложенные элементы
    for el in obj.iter():
        # берём «листья»: не сам объект, без вложенных элементов, с непустым текстом
        if el is not obj and len(el) == 0 and el.text and el.text.strip():
            # отдаём элемент и имя поля без пространства имён
            yield el, local(el.tag)


