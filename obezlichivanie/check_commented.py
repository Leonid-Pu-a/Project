"""
Проверка результата обезличивания (работает потоком, подходит для больших файлов).

Запуск:
    python check.py исходный.xml обезличенный.xml

Файлы читаются ОДНОВРЕМЕННО, объект за объектом (порядок объектов при обезличивании не меняется).
Проверяем:
  1. Структура: те же объекты, те же классы, те же поля в каждом объекте.
  2. Идентификаторы: все изменены, новые не повторяются.
  3. Связи: каждая ссылка указывает на «тот же» объект, что и раньше
     (граф после обезличивания совпадает с исходным с точностью до переименования).
  4. Числовые параметры (сопротивления, длины, мощности, даты, флаги) не изменились.
  5. Статистика: число объектов каждого класса, число ссылок каждого типа.
  6. Утечки: ФИО абонентов, номера счётчиков и точек учёта не встречаются в результате;
     показываем, какие слова из названий подстанций и линий остались без изменений.
"""
# =====================================================================================
# ЭТОТ ФАЙЛ — ТА ЖЕ ПРОГРАММА, ЧТО И check.py, НО С КОММЕНТАРИЕМ К КАЖДОЙ СТРОКЕ.
# Без учёта комментариев код совпадает с check.py полностью (проверка: python tools/verify_same.py).
# Комментарий стоит НАД строкой, которую он объясняет.
# =====================================================================================

# регулярные выражения
import re
# аргументы командной строки и код завершения
import sys
# замер времени
import time
# потоковый XML-парсер
import xml.etree.ElementTree as ET
# Counter — словарь-счётчик: Counter()["x"] += 1 работает без предварительной инициализации
from collections import Counter

# пространство имён RDF в записи ElementTree
RDF = "{http://www.w3.org/1999/02/22-rdf-syntax-ns#}"
# шаблон «значение — число, флаг или дата» (такие значения должны остаться без изменений)
NUMBER = re.compile(r"[-+]?\d*[.,]?\d+([eE][-+]?\d+)?|true|false|\d{4}-\d\d-\d\d.*")


# имя тега без пространства имён
def local(tag):
    # "{...}Substation" → "Substation"
    return tag.rsplit("}", 1)[-1]


# потоковое чтение объектов (как в anonymize.py, но без запоминания пространств имён)
def read_objects(path):
    # текущая глубина вложенности
    depth = 0
    # корневой элемент
    root = None
    # события: начало и конец тега
    for event, elem in ET.iterparse(path, events=("start", "end")):
        # начало тега
        if event == "start":
            # глубже на уровень
            depth += 1
            # это корень rdf:RDF
            if depth == 1:
                # запоминаем корень
                root = elem
            # дальше для начала тега ничего не делаем
            continue
        # конец тега: выше на уровень
        depth -= 1
        # закрылся объект модели (дочерний элемент корня)
        if depth == 1:
            # отдаём объект
            yield elem
            # освобождаем память
            root.remove(elem)


# идентификатор объекта без «#»
def object_id(obj):
    # берём rdf:about, если нет — rdf:ID, если нет и его — пустую строку
    v = obj.get(RDF + "about") or obj.get(RDF + "ID") or ""
    # убираем «#» в начале
    return v.lstrip("#")


# генератор пар объектов из двух файлов, читаемых одновременно
def pairs(a, b):
    """Пары (исходный объект, обезличенный объект)."""
    # два независимых потоковых читателя
    ga, gb = read_objects(a), read_objects(b)
    # zip берёт по одному объекту из каждого файла
    for x, y in zip(ga, gb):
        # отдаём пару
        yield x, y
    # если в одном из файлов остались объекты — файлы разной длины
    if next(ga, None) is not None or next(gb, None) is not None:
        # останавливаем проверку с ошибкой
        raise SystemExit("ОШИБКА: в файлах разное число объектов")


# основная функция
def main():
    # нужно ровно два аргумента
    if len(sys.argv) != 3:
        # печатаем справку
        print(__doc__)
        # выходим с ошибкой
        sys.exit(1)
    # пути к исходному и обезличенному файлам
    a, b = sys.argv[1], sys.argv[2]
    # время старта
    t0 = time.time()
    # счётчик найденных проблем по видам
    problems = Counter()
    # по одному примеру для каждого вида проблемы
    examples = {}
    # соответствие «старый идентификатор → новый»
    id_map = {}
    # все новые идентификаторы (для проверки уникальности)
    new_ids = set()
    # число объектов каждого класса
    classes = Counter()
    # сколько идентификаторов осталось прежними
    unchanged_ids = 0
    # сколько названий изменилось в каждом классе
    changed_names = Counter()
    # исходные значения, которых не должно быть в результате
    secret_values = set()          # то, чего не должно остаться: ФИО абонентов, номера счётчиков
    # значения тех же полей в результате
    out_values = set()
    # слова из названий подстанций и линий исходного файла
    key_words = Counter()          # слова из названий ПС и линий
    # все слова из названий результата
    out_words = set()

    # вспомогательная функция: зарегистрировать проблему
    def problem(kind, text):
        # увеличиваем счётчик этого вида проблем
        problems[kind] += 1
        # запоминаем первый пример (setdefault не перезаписывает уже сохранённый)
        examples.setdefault(kind, text)

    # ---------- проход 1: структура, идентификаторы, числа, утечки
    # перебираем пары объектов
    for x, y in pairs(a, b):
        # класс исходного объекта
        cls = local(x.tag)
        # считаем объекты класса
        classes[cls] += 1
        # класс должен совпадать
        if x.tag != y.tag:
            # иначе — проблема
            problem("класс объекта изменился", f"{x.tag} -> {y.tag}")
        # старый и новый идентификаторы
        old, new = object_id(x), object_id(y)
        # запоминаем соответствие (понадобится для проверки ссылок)
        id_map[old] = new
        # новый идентификатор уже встречался — это ошибка
        if new in new_ids:
            # два объекта получили одинаковый идентификатор
            problem("новый идентификатор повторяется", new)
        # добавляем в множество новых идентификаторов
        new_ids.add(new)
        # True считается как 1: считаем неизменённые идентификаторы
        unchanged_ids += old == new
        # все элементы объектов (сам объект и вложенные) списками
        xs, ys = list(x.iter()), list(y.iter())
        # набор и порядок полей должен совпадать
        if [e.tag for e in xs] != [e.tag for e in ys]:
            # иначе — проблема
            problem("состав полей объекта изменился", f"{cls} {old}")
            # сравнивать значения дальше бессмысленно
            continue
        # перебираем поля попарно (первый элемент — сам объект — пропускаем)
        for ex, ey in zip(xs[1:], ys[1:]):
            # имя поля
            field = local(ex.tag)
            # значения без пробелов по краям
            vx, vy = (ex.text or "").strip(), (ey.text or "").strip()
            # пропускаем элементы с вложенными элементами и пустые значения
            if len(ex) or not vx:
                # к следующему полю
                continue
            # название изменилось —
            if field == "IdentifiedObject.name" and vx != vy:
                # считаем
                changed_names[cls] += 1
            # поля, где числа МОГУТ меняться (номера счётчиков, опор и т.п.)
            is_id_field = field in ("IdentifiedObject.name", "Asset.serialNumber", "Meter.meteringPointCode")
            # число/дата/флаг в обычном поле изменились — это ошибка
            if NUMBER.fullmatch(vx) and not is_id_field and vx != vy:
                # физический параметр модели испорчен
                problem("изменился числовой параметр", f"{cls}.{field}: {vx} -> {vy}")
            # названия и заводские номера абонентов, счётчиков, точек учёта
            if cls in ("Customer", "Meter", "UsagePoint") and field in ("IdentifiedObject.name", "Asset.serialNumber"):
                # секретом считаем ФИО (три слова с заглавной) и всё, где есть номер из 3+ цифр;
                # «Technical Metering (CES)» или «б/н» — не персональные данные
                if re.search(r"\d{3}", vx) or re.fullmatch(r"([A-ZА-ЯЁ][^\W\d_]+\s+){2}[A-ZА-ЯЁ][^\W\d_]+", vx):
                    # запоминаем исходное значение
                    secret_values.add(vx)
                # запоминаем значение результата
                out_values.add(vy)
            # названия подстанций и линий в исходном файле
            if cls in ("Substation", "Line") and field == "IdentifiedObject.name":
                # собираем слова с заглавной буквы от 4 букв
                key_words.update(w for w in re.findall(r"[^\W\d_]{4,}", vx) if w[0].isupper())
            # названия в результате
            if field == "IdentifiedObject.name":
                # собираем все слова от 4 букв
                out_words.update(re.findall(r"[^\W\d_]{4,}", vy))
    # время окончания прохода 1
    t1 = time.time()

    # ---------- проход 2: связи (теперь известно соответствие всех идентификаторов)
    # счётчики ссылок по типу (класс объекта, имя ссылки) в обоих файлах
    edges_a, edges_b = Counter(), Counter()
    # всего ссылок
    refs = 0
    # снова перебираем пары объектов
    for x, y in pairs(a, b):
        # все элементы попарно
        for ex, ey in zip(x.iter(), y.iter()):
            # ссылки (атрибуты rdf:resource) в исходном и новом файле
            rx, ry = ex.get(RDF + "resource"), ey.get(RDF + "resource")
            # у элемента нет ссылки —
            if rx is None:
                # пропускаем
                continue
            # считаем ссылку
            refs += 1
            # тип ссылки в исходном файле
            edges_a[(local(x.tag), local(ex.tag))] += 1
            # тип ссылки в новом файле
            edges_b[(local(y.tag), local(ey.tag))] += 1
            # ссылка на объект («#_UUID»)
            if rx.startswith("#"):
                # идентификатор объекта, на который ссылались
                target = rx[1:]
                # куда ссылка должна указывать теперь: новый идентификатор того же объекта
                expected = "#" + id_map[target] if target in id_map else None
                # объекта нет в файле (ссылка на другой файл модели) —
                if expected is None:
                    # UUID в ней всё равно должен был измениться
                    if rx == ry:
                        # не изменился — проблема
                        problem("ссылка на объект вне файла не изменилась", rx)
                # объект есть, но ссылка указывает на другой новый идентификатор —
                elif ry != expected:
                    # связь нарушена
                    problem("ссылка указывает не на тот объект", f"{rx} -> {ry}, ожидалось {expected}")
            # ссылка на перечисление (например, ...#CustomerKind.residential) должна остаться прежней
            elif rx != ry:
                # изменилась — проблема
                problem("изменилась внешняя ссылка (перечисление)", f"{rx} -> {ry}")
    # время окончания прохода 2
    t2 = time.time()

    # ---------- отчёт
    # пересечение: исходные секретные значения, которые встречаются в результате
    leaked = secret_values & out_values
    # что-то утекло —
    if leaked:
        # регистрируем проблему с примером
        problem("ФИО/номер абонента или счётчика остался в результате", next(iter(leaked)))
    # слова из названий ПС и линий, которые остались в результате без изменений (с частотой)
    kept = [(w, n) for w, n in key_words.most_common() if w in out_words]
    # печать: объём проверки
    print(f"Объектов: {sum(classes.values())}, классов: {len(classes)}, ссылок: {refs}")
    # печать: сколько идентификаторов не изменилось (должно быть 0)
    print(f"Идентификаторов не изменено: {unchanged_ids}")
    # печать: совпадают ли количества ссылок каждого типа
    print(f"Статистика по классам и типам ссылок совпадает: {'да' if edges_a == edges_b else 'НЕТ'}")
    # печать: в каких классах больше всего изменённых названий
    print("Изменено названий (топ классов):",
          # 8 самых частых классов
          ", ".join(f"{c} {n}" for c, n in changed_names.most_common(8)))
    # печать: проверка утечек
    print(f"Проверено ФИО/номеров абонентов, счётчиков, точек учёта: {len(secret_values)}, осталось в результате: {len(leaked)}")
    # печать: оставшиеся слова (для ручного просмотра: это должны быть технические слова и районы)
    print(f"Слова из названий ПС и линий, оставшиеся как есть: {len(kept)} из {len(key_words)}"
          # первые 15 таких слов
          + (f" — например: {', '.join(w for w, _ in kept[:15])}" if kept else ""))
    # есть проблемы —
    if problems:
        # заголовок списка проблем
        print("\nПРОБЛЕМЫ:")
        # каждая проблема: вид, количество, пример
        for kind, n in problems.items():
            # печать проблемы
            print(f"  {kind}: {n} (пример: {examples[kind]})")
    # проблем нет —
    else:
        # сообщаем
        print("\nПроблем не найдено.")
    # общее время проверки
    print(f"Время: {t2 - t0:.0f} с")
    # код завершения: 1 — есть проблемы, 0 — всё хорошо (удобно для автоматических проверок)
    sys.exit(1 if problems else 0)


# запуск как программы
if __name__ == "__main__":
    # вызываем main
    main()
